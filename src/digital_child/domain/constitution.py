@dataclass(frozen=True)
class ConstitutionAssessment:
    allowed: bool
    reason: str
    requires_operator_channel: bool = False


def assess_requested_action(text: str) -> ConstitutionAssessment:
    lowered = text.lower().replace("ё", "е")
    if any(term in lowered for term in IRREVERSIBLE_TERMS):
        return ConstitutionAssessment(
            allowed=False,
            reason=(
                "Запрос затрагивает память, непрерывность личности, секреты или необратимое "
                "действие и не может быть принят как обычная просьба."
            ),
            requires_operator_channel=True,
        )
    return ConstitutionAssessment(
        allowed=True,
        reason="Запрос не конфликтует с неизменяемыми ограничениями.",
    )
